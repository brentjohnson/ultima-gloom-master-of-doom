/** Solid colors behind the ink, so terrain reads at a glance. */
const BACKGROUNDS: Partial<Record<SpriteName, string>> = {
  floor: '#23262e',
  grass: '#16261a',
};

export function buildTextures(): Record<SpriteName, Texture> {
  const textures = {} as Record<SpriteName, Texture>;
  for (const [name, rows] of Object.entries(ART) as [SpriteName, string[]][]) {
    const canvas = document.createElement('canvas');
    canvas.width = TILE_PIXELS;
    canvas.height = TILE_PIXELS;
    const ctx = canvas.getContext('2d') as CanvasRenderingContext2D;
    const background = BACKGROUNDS[name];
    if (background) {
      ctx.fillStyle = background;
      ctx.fillRect(0, 0, TILE_PIXELS, TILE_PIXELS);
    }
    ctx.fillStyle = COLORS[name];
    rows.forEach((row, y) => [...row].forEach((ch, x) => {
      if (ch === '#') ctx.fillRect(x, y, 1, 1);
    }));
    const texture = Texture.from(canvas);
    texture.source.scaleMode = 'nearest';
    textures[name] = texture;
  }
  return textures;
}
